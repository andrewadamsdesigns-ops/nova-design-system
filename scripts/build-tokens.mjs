// Turns tokens/tokens.json into src/styles/tokens.css.
// Base tokens become --nv-<group>-<name> on :root.
// Each theme becomes a [data-theme="<name>"] block of semantic --nv-<name> variables.
// The "nova" theme is also the :root default, so the system works with no attribute set.
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const root = new URL('..', import.meta.url)
const tokens = JSON.parse(readFileSync(new URL('tokens/tokens.json', root), 'utf8'))

const skip = (k) => k.startsWith('$')
const lines = ['/* Generated by scripts/build-tokens.mjs from tokens/tokens.json. Do not edit by hand. */', '']

lines.push(':root {')
for (const [group, values] of Object.entries(tokens.base)) {
  for (const [name, value] of Object.entries(values)) {
    if (!skip(name)) lines.push(`  --nv-${group}-${name}: ${value};`)
  }
}
lines.push('}', '')

const themeBlock = (selector, theme) => {
  lines.push(`${selector} {`)
  for (const [name, value] of Object.entries(theme)) {
    if (!skip(name)) lines.push(`  --nv-${name}: ${value};`)
  }
  lines.push('}', '')
}

themeBlock(':root, [data-theme="nova"]', tokens.themes.nova)
for (const [name, theme] of Object.entries(tokens.themes)) {
  if (name !== 'nova') themeBlock(`[data-theme="${name}"]`, theme)
}

const out = fileURLToPath(new URL('src/styles/tokens.css', root))
writeFileSync(out, lines.join('\n'))
console.log(`tokens.css written: ${Object.keys(tokens.themes).length} themes`)
